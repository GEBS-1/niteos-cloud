def build_router_image_prompt(
    *,
    task: str,
    facade_mode: str = "auto",
) -> str:
    hint = FACADE_HINTS.get(facade_mode, FACADE_HINTS["auto"])
    task_block = task.strip()
    if "Уточнения:" not in task_block:
        task_block = f"{task_block}\n\nУточнения:\n- {hint}"
    prompt = (
        "AI-визуализатор архитектурной подсветки.\n\n"
        "Изображения:\n"
        "- исходное фото фасада;\n\n"
        "Сделай одну реалистичную ночную визуализацию подсветки строго по исходному фото.\n\n"
        f"Style: {ROUTER_STYLE_BLOCK}\n\n"
        f"Задание: {task_block}\n\n"
        "Правила:\n"
        "- сохранить геометрию здания, этажность, окна, двери, стекло, фасадные панели и материалы;\n"
        "- не добавлять людей, машины, новые вывески, логотипы, новые окна и лишние объекты;\n"
        "- затемнить сцену естественно, свет должен мягко ложиться на фасад;\n"
        "- не делать схему, мультяшность, грубый Photoshop или плоские цветные полосы.\n\n"
        f"{PROMPT_GLOBAL_COVERAGE_QUALITY}\n\n"
        "Итог: одна финальная презентационная картинка без текста и интерфейса."
    )
    return append_facade_identity_lock(prompt)

def router_task_for_scenario(scenario_id: str, fallback_app: str = "") -> str:
    if scenario_id in SCENARIO_ROUTER_TASKS:
        return SCENARIO_ROUTER_TASKS[scenario_id]
    if fallback_app.strip():
        return (
            "Реалистичный ночной рендер архитектурной подсветки фасада для презентации заказчику. "
            f"Цвет: 5000К. Свет: {fallback_app.strip()}. Цвет: 5000К."
        )
    return (
        "Реалистичный ночной рендер архитектурной подсветки фасада для презентации заказчику. Цвет: 5000К."
    )


