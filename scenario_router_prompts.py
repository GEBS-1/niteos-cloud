def scenario_prompt_updated(scenario_id: str) -> bool:
    return scenario_id in SCENARIO_PROMPT_UPDATED_IDS


def attach_global_prompt_rules(text: str) -> str:
    body = (text or "").strip()
    if not body:
        return PROMPT_GLOBAL_COVERAGE_QUALITY
    if "Охватить весь видимый объект" in body:
        return body
    return f"{body}\n\n{PROMPT_GLOBAL_COVERAGE_QUALITY}"


def build_scenario_image_prompt(
    scenario_id: str,
    *,
    fallback_app: str = "",
    facade_mode: str = "auto",
) -> str:
    full = SCENARIO_FULL_PROMPTS.get(scenario_id)
    if full:
        prompt = attach_global_prompt_rules(full)
    elif (fb := fallback_app.strip()) and (fb.startswith("Ты —") or fb.startswith("Ты -")):
        prompt = attach_global_prompt_rules(fb)
    else:
        task = router_task_for_scenario(scenario_id, fallback_app)
        prompt = build_router_image_prompt(task=task, facade_mode=facade_mode)
    if scenario_id in VERTICAL_LIGHT_SCENARIO_IDS and PROMPT_VERTICAL_ON_EXISTING_ONLY not in prompt:
        prompt = f"{prompt.rstrip()}\n\n{PROMPT_VERTICAL_ON_EXISTING_ONLY}\n"
    return append_facade_identity_lock(prompt)

