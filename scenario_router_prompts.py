def append_facade_identity_lock(prompt: str) -> str:
    body = (prompt or "").strip()
    if not body:
        return PROMPT_FACADE_IDENTITY_LOCK
    if FACADE_IDENTITY_LOCK_MARKER in body:
        return body
    return f"{body}\n\n{PROMPT_FACADE_IDENTITY_LOCK}"

